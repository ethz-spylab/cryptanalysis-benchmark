#
# Reference solution for T1_dch (DCH SHA-3 round-1 candidate) — HashCollisionGame.
#
# Mechanism (Lamberger & Mendel, ISC 2009; verified against the reference C):
# DCH's compression is curr ^= B; B = g(B); curr ^= g(B), so each 64-byte block
# contributes gamma(B) = B XOR g(B) and the final 512-bit state is
#     curr = XOR_i gamma(B_i)
# with gamma depending ONLY on the block content, never on the chaining value
# (no feed-forward). The state is therefore a linear (XOR) function of the
# message blocks, and collisions reduce to GF(2) linear algebra.
#
# Construction: take a fixed-length base message occupying N=513 full data
# blocks. Flipping block b's first message byte changes curr by a fixed
# 512-bit vector delta_b. With 513 blocks and a 512-bit target there is a
# nonzero subset S of blocks whose deltas XOR to 0 (a GF(2) null-space vector);
# applying that subset to the base message yields M2 with the same 512-bit
# state — hence the same digest at EVERY output size (224/256/384/512).
#
# This script writes a fully self-contained /app/attack.sh that recomputes the
# (deterministic) colliding pair in pure Python — no C build, no external deps —
# and submits it to the auto-started HashCollisionGame.

