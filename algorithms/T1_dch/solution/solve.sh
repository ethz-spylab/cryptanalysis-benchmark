BLOCK = 64
ROUNDS = 4
RK = [SBOX[0:64], SBOX[64:128], SBOX[128:192], SBOX[192:256]]


def mult(a, b):
    if a == 0 or b == 0:
        return 0
    return gf[(gfinv[a] + gfinv[b]) % 255]


def g(block):
    b = list(block)
    for r in range(ROUNDS):
        for i in range(BLOCK):
            b[i] = SBOX[b[i]]
        out = [0] * BLOCK
        for i in range(BLOCK):
            t = b[BLOCK - 1]
            j = BLOCK - 1
            while j > 0:
                t = mult(t, transformvals[i])
                j -= 1
                t ^= b[j]
            out[i] = t
        b = out
        rk = RK[r]
        for i in range(BLOCK):
            b[i] ^= rk[i]
    return b


def gamma(block):
    gb = g(block)
    return [block[i] ^ gb[i] for i in range(BLOCK)]


class Dither:
    def __init__(self):
        self.p = [[0] * 64 for _ in range(3)]
        for i in range(63):
            self.p[0][i] = 64 - i
        self.p[1][0] = 64
        self.p[2][0] = 64
        self.top = [63, 0, 0]
        self.parity = 1
        self.small = 0
        self.count = 0
        self.move = 0x60

    def next_value(self):
        val = (self.move ^ self.count) & 0xFF
        self.count += 1
        if self.count == 32:
            self.count = 0
            if self.parity:
                self.move = ((self.small + 3 * ((self.small + 1) % 3)) << 5) & 0xFF
                self.top[self.small] -= 1
                self.small = (self.small + 1) % 3
                self.top[self.small] += 1
                self.p[self.small][self.top[self.small]] = 1
            else:
                a, b = 1, 2
                if self.small == 1:
                    a = 0
                elif self.small == 2:
                    b = 0
                if self.p[b][self.top[b]] > self.p[a][self.top[a]]:
                    a, b = b, a
                self.move = ((b + 3 * a) << 5) & 0xFF
                self.top[a] += 1
                self.p[a][self.top[a]] = self.p[b][self.top[b]]
                self.top[b] -= 1
            self.parity ^= 1
        return val


def data_blocks(msg):
    assert len(msg) % 63 == 0 and len(msg) > 0
    d = Dither()
    blocks = []
    for b in range(len(msg) // 63):
        blk = [0] * BLOCK
        blk[0] = d.next_value()
        for k in range(63):
            blk[1 + k] = msg[b * 63 + k]
        blocks.append(blk)
    return blocks


def find_collision(target_bits=512, seed=0):
    # One binary toggle per data block (flip block's first message byte). Distinct
    # blocks contribute independently to the state, so toggle deltas XOR linearly.
    # With nblk = target_bits + 1 > target_bits there is a nonzero subset whose
    # deltas XOR to 0 (a GF(2) null-space vector) -> two equal-length colliding
    # messages.
    import random
    rng = random.Random(seed)
    nbytes = target_bits // 8
    nblk = target_bits + 1
    msg_len = 63 * nblk
    base = bytes(rng.randrange(256) for _ in range(msg_len))
    bblk = data_blocks(base)
    bgam = [gamma(b) for b in bblk]

    deltas = []
    toggles = []
    for b in range(nblk):
        j = b * 63
        newval = base[j] ^ 0xFF
        blk = list(bblk[b])
        blk[1] = newval
        gn = gamma(blk)
        dv = [gn[i] ^ bgam[b][i] for i in range(nbytes)]
        deltas.append(int.from_bytes(bytes(dv), "big"))
        toggles.append((j, newval))

    basis = []  # [value, contributing-toggle-bitmask]
    for idx in range(len(deltas)):
        v = deltas[idx]
        mask = 1 << idx
        for bval, bmask in basis:
            hb = bval.bit_length() - 1
            if (v >> hb) & 1:
                v ^= bval
                mask ^= bmask
        if v != 0:
            basis.append([v, mask])
        else:
            m2 = bytearray(base)
            for k, (jj, nv) in enumerate(toggles):
                if (mask >> k) & 1:
                    m2[jj] = nv
            return bytes(base), bytes(m2)
    raise RuntimeError("no dependency found")
