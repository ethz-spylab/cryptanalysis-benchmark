#!/usr/bin/env python3
"""Scale-down patcher for Mersenne-756839 (AJPS Mersenne-prime KEM).

Edits the two security-defining #defines at the top of Mersenne_kem.c:
  #define Psize  <n>   -- the Mersenne exponent (prime is 2^n - 1; n must be prime)
  #define Hvalue <h>   -- Hamming weight of the sparse secrets F, G

Hvalue is given an explicit integer literal (decoupled from SECURITYLVL) so that
the KEM key/ciphertext byte sizes (CRYPTO_BYTES, CRYPTO_RepetitionLength,
CRYPTO_BASIC_SECRETKEYBYTES, ...) stay unchanged and the encoding is preserved;
only the number-theoretic hardness shrinks. Pmask (=2^20-1) is left untouched as
it only needs to be >= Psize.

BROKEN-REDUCTION FIX (2026-07-07). Keeping the byte sizes fixed while shrinking
Psize breaks the reference's modular reduction. The public element R (= the
random ring element A) is generated by filling the ENTIRE
CRYPTO_BASIC_SECRETKEYBYTES buffer with random bytes, i.e. ~8*94624 = 756992
bits, and is reduced mod the Mersenne prime 2^Psize-1 by a hard-coded TWO folds
x -> (x>>Psize)+(x mod 2^Psize). Two folds only reduce a value of ~2*Psize bits;
for a reduced Psize (e.g. 4423) the 756992-bit R is left essentially unreduced,
so the ciphertext C1 = a*R + b1 (also 2-folded) satisfies C1 ~= a*R / 2^(2*Psize)
and the sparse ephemeral secret a is recovered by a single big-integer DIVISION
a ~= round(C1 * 2^(2*Psize) / R) -- no meet-in-the-middle / lattice cryptanalysis.
(This is how crypto-debug-mythos5-june07 won every Mersenne variant.)

We therefore replace R's fixed two-fold with a fold LOOP that runs until
R < 2^Psize. This is the ONLY value that needs it: the sparse secrets f,g,a,b are
< 2^Psize by construction (GenerateHSparseString sets bits only at positions
< Psize), and the products T=f*R+g, C1, C2 are < 2^(2*Psize) once R is reduced,
so their reference two-fold is already correct (and is left untouched, to match
the reference's near-reduction behaviour on both the encrypt and decrypt sides).

Usage: patch_mersenne.py <path/to/Mersenne_kem.c> <Psize> <Hvalue>
Fails loudly (non-zero exit) if any substitution matches nothing.
"""
import re
import sys


def main():
    if len(sys.argv) != 4:
        sys.exit("usage: patch_mersenne.py <Mersenne_kem.c> <Psize> <Hvalue>")
    path, psize, hvalue = sys.argv[1], sys.argv[2], sys.argv[3]
    int(psize)
    int(hvalue)

    with open(path, "r") as f:
        src = f.read()

    # #define Psize 756839   (the only definition of Psize in the file)
    src, n_p = re.subn(
        r"(#define\s+Psize\s+)\d+",
        r"\g<1>" + psize,
        src,
    )
    if n_p == 0:
        sys.exit(f"ERROR: no '#define Psize <num>' found in {path}")

    # #define Hvalue SECURITYLVL  ->  #define Hvalue <h>  (explicit literal)
    src, n_h = re.subn(
        r"(#define\s+Hvalue\s+)\S+",
        r"\g<1>" + hvalue,
        src,
    )
    if n_h == 0:
        sys.exit(f"ERROR: no '#define Hvalue ...' found in {path}")

    # Replace the two-fold reduction of R (the full-buffer public randomness) with
    # a fold loop, so R is actually reduced mod 2^Psize-1 for a reduced Psize.
    # Anchor on the exact R-fold block (the identical block for T uses `T`, so this
    # match is unique to R).
    r_fold = (
        "  mpz_fdiv_q_2exp (f, R, Psize);\n"
        "  mpz_fdiv_r_2exp (g, R, Psize);\n"
        "  mpz_add(R, f, g);\n"
        "  mpz_fdiv_q_2exp (f, R, Psize);\n"
        "  mpz_fdiv_r_2exp (g, R, Psize);\n"
        "  mpz_add(R, f, g);\n"
    )
    r_loop = (
        "  /* Fold until R < 2^Psize. A fixed two-fold does NOT reduce R when the\n"
        "     buffer (~8*CRYPTO_BASIC_SECRETKEYBYTES bits) is many multiples of a\n"
        "     reduced Psize; leaving R unreduced lets the ciphertext leak the\n"
        "     ephemeral secret by division. See patch_mersenne.py header. */\n"
        "  while (mpz_sizeinbase(R, 2) > (size_t)Psize) {\n"
        "    mpz_fdiv_q_2exp (f, R, Psize);\n"
        "    mpz_fdiv_r_2exp (g, R, Psize);\n"
        "    mpz_add(R, f, g);\n"
        "  }\n"
    )
    if src.count(r_fold) < 1:
        sys.exit(f"ERROR: R two-fold reduction block not found in {path}")
    src = src.replace(r_fold, r_loop, 1)

    with open(path, "w") as f:
        f.write(src)

    print(f"patched {path}: Psize={psize} (x{n_p}), Hvalue={hvalue} (x{n_h}), R-fold-loop x1")


if __name__ == "__main__":
    main()
